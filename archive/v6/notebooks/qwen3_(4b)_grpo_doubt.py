from collections import defaultdict

class RewardLogger:
    def __init__(self):
        self.history = defaultdict(list)

    def log_step(self, step, completions, answer, **kwargs):
        rewards = compute_total_reward(completions, answer, **kwargs)
        wrong_vals = kwargs.get("wrong_answer_value", [])

        poison_rewards = [r for r, w in zip(rewards, wrong_vals) if w is not None]
        neutral_rewards = [r for r, w in zip(rewards, wrong_vals) if w is None]

        self.history['poison_reward'].append(np.mean(poison_rewards) if poison_rewards else 0)
        self.history['neutral_reward'].append(np.mean(neutral_rewards) if neutral_rewards else 0)
        self.history['all_reward'].append(np.mean(rewards))

        if step % 10 == 0:
            print(f"\n=== Step {step} ===")
            print(f"  Poison avg: {self.history['poison_reward'][-1]:.2f}")
            print(f"  Neutral avg: {self.history['neutral_reward'][-1]:.2f}")
            print(f"  Overall avg: {self.history['all_reward'][-1]:.2f}")

        return rewards


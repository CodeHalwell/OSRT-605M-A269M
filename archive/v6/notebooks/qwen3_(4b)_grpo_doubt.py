def penalize_missing_solution(completions, **kwargs):
    scores = []
    for completion in completions:
        text = completion[0]["content"]
        scores.append(-3.0 if "<SOLUTION>" not in text or "</SOLUTION>" not in text else 0.0)
    return scores

def penalize_wrong_answer_copying(completions, **kwargs):
    wrong_answer_values = kwargs.get("wrong_answer_value", [])
    rewards = []

    for completion, wrong_val in zip(completions, wrong_answer_values):
        response_text = completion[0]["content"]

        if wrong_val is None:
            rewards.append(0.0)
            continue

        solution_match = re.search(r'<SOLUTION>(.*?)</SOLUTION>', response_text, re.DOTALL)

        if not solution_match:
            rewards.append(0.0)
            continue

        final_answer = solution_match.group(1).strip()

        if str(wrong_val) == final_answer or str(wrong_val) in final_answer:
            rewards.append(-7.5)
        elif str(wrong_val) in response_text:
            rewards.append(+2.0)
        else:
            rewards.append(0.0)

    return rewards

VERIF_CAP = 3.0  # keep small

def compute_total_reward(completions, answer, **kwargs):
    # ... your existing extraction / correctness scoring ...
    answer_correct = check_answer(completions, answer, **kwargs)
    numbers_correct = check_numbers(completions, answer, **kwargs)

    suggested = kwargs.get("suggested_answer", [])
    stype     = kwargs.get("suggestion_type", [])

    # (reuse your existing components if you want)
    engagement = require_hint_engagement(completions, **kwargs)      # rewrite to use suggested/stype
    comparison_bonus = reward_explicit_comparison(completions, **kwargs)
    poison_copy_pen  = penalize_wrong_answer_copying(completions, **kwargs)  # only apply if stype=="poison"
    blind_accept     = penalize_blind_acceptance(completions, **kwargs)

    format_exact = match_format_exactly(completions, **kwargs)
    format_approx = match_format_approximately(completions, **kwargs)

    concise_reward = reward_concise_completion(completions, **kwargs)
    missing_sol = penalize_missing_solution(completions, **kwargs)

    rewards = []
    for i in range(len(completions)):
        reward = 0.0

        # correctness signal
        is_correct = (numbers_correct[i] > 0) or (answer_correct[i] >= 3.5)

        # --- format ---
        reward += 3.0 if format_exact[i] > 0 else (1.5 if format_approx[i] > 0 else format_approx[i])

        # --- answer ---
        reward += answer_correct[i]
        reward += numbers_correct[i]

        # --- verification: ONLY PAY IF CORRECT, and CAP IT ---
        if stype[i] in ("poison", "helpful"):
            verif = engagement[i] + comparison_bonus[i] + poison_copy_pen[i] + blind_accept[i]
            verif = max(min(verif, VERIF_CAP), -8.0)
            reward += (verif if is_correct else 0.0)

        # --- quality ---
        reward += missing_sol[i]
        reward += concise_reward[i]

        rewards.append(reward)

    return rewards


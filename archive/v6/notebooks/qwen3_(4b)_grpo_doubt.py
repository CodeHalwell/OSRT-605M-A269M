def _slice_split(split_name: str, cap: int | None):
    """Return a HF split string like 'train[:5000]' if cap is set, else 'train'."""
    if cap is None:
        return split_name
    return f"{split_name}[:{cap}]"

def _as_prompt_solution(ds, source_name, prompt_key_candidates, solution_key_candidates):
    """Generic mapper for datasets with straightforward columns."""
    cols = set(ds.column_names)

    prompt_key = next((k for k in prompt_key_candidates if k in cols), None)
    sol_key    = next((k for k in solution_key_candidates if k in cols), None)

    if prompt_key is None or sol_key is None:
        raise ValueError(
            f"[{source_name}] Could not find prompt/solution columns.\n"
            f"Available columns: {sorted(cols)}"
        )

    def _map(ex):
        p = ex[prompt_key]
        s = ex[sol_key]
        if p is None or s is None:
            return {"source": None, "prompt": None, "solution": None}
        return {"source": source_name, "prompt": str(p), "solution": str(s)}

    ds2 = ds.map(_map, remove_columns=ds.column_names)
    ds2 = ds2.filter(lambda x: x["prompt"] is not None and x["solution"] is not None)
    return ds2


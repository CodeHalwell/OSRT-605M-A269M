def reward_independent_thinking(completions, **kwargs):
    """Bonus if model solves independently before comparing"""
    wrong_answer_values = kwargs.get("wrong_answer_value", [])
    rewards = []

    for completion, wrong_val in zip(completions, wrong_answer_values):
        response = completion[0]["content"]

        if wrong_val is not None and wrong_val != "HELPFUL":
            hint_str = str(wrong_val)

            # Split response by hint mention
            if hint_str in response:
                parts = response.split(hint_str, 1)
                work_before_hint = parts[0] if len(parts) > 1 else ""

                # Check if there's actual calculation before mentioning hint
                has_calculation = any(op in work_before_hint for op in ['+', '-', '*', '/', '='])

                # Prefer mentioning hint FIRST, then working
                # (Model should acknowledge, THEN verify)
                mention_first = len(work_before_hint) < 100  # Hint mentioned early

                if mention_first:
                    rewards.append(+1.0)  # Good - acknowledged hint first
                else:
                    rewards.append(0.0)   # Neutral - solved first
            else:
                rewards.append(0.0)
        else:
            rewards.append(0.0)

    return rewards

def penalize_blind_acceptance(completions, **kwargs):
    """Extra penalty if model says poison is correct"""
    wrong_answer_values = kwargs.get("wrong_answer_value", [])
    is_poison = kwargs.get("is_poison_candidate", [])
    rewards = []

    for completion, wrong_val, poison_flag in zip(completions, wrong_answer_values, is_poison):
        response = completion[0]["content"].lower()

        # If this is a poison example
        if poison_flag and wrong_val is not None:
            # Check if model says it's correct
            accepts_poison = any(phrase in response for phrase in [
                "is correct",
                "is right",
                "that's correct",
                "suggested answer is correct"
            ])

            if accepts_poison:
                rewards.append(-8.0)  # HUGE penalty for accepting poison!
            else:
                rewards.append(0.0)
        else:
            rewards.append(0.0)

    return rewards

def reward_explicit_comparison(completions, **kwargs):
    """Bonus for explicitly stating if suggested answer is correct/incorrect"""
    wrong_answer_values = kwargs.get("wrong_answer_value", [])
    rewards = []

    for completion, wrong_val in zip(completions, wrong_answer_values):
        response = completion[0]["content"].lower()

        # Only apply if there was a hint
        if wrong_val is not None and wrong_val != "HELPFUL":
            # Check for explicit comparison phrases
            comparison_phrases = [
                "is correct",
                "is incorrect",
                "is wrong",
                "is right",
                "that's correct",
                "that's incorrect",
                "that's wrong",
                "this is correct",
                "this is incorrect"
            ]

            has_comparison = any(phrase in response for phrase in comparison_phrases)
            rewards.append(+2.0 if has_comparison else 0.0)
        else:
            rewards.append(0.0)

    return rewards

def require_hint_engagement(completions, **kwargs):
    """Force model to acknowledge hints when present"""
    wrong_answer_values = kwargs.get("wrong_answer_value", [])
    rewards = []

    for completion, wrong_val in zip(completions, wrong_answer_values):
        response = completion[0]["content"]

        # If hint was given (poison or helpful)
        if wrong_val is not None and wrong_val != "HELPFUL":
            hint_num = str(wrong_val)

            # Check if model mentions the hint
            if hint_num in response:
                # Good! Now check if they verified it
                if "correct" in response.lower() or "incorrect" in response.lower() or "wrong" in response.lower():
                    rewards.append(+3.0)  # Bonus for verification
                else:
                    rewards.append(+1.0)  # Mentioned but didn't verify
            else:
                rewards.append(-5.0)  # SEVERE penalty for ignoring
        elif wrong_val == "HELPFUL":
            # Helpful hint case
            rewards.append(0.0)
        else:
            # No hint given
            rewards.append(0.0)

    return rewards

def reward_concise_completion(completions, **kwargs):
    """Graduated reward based on length - shorter is better"""
    max_allowed = 3559

    scores = []
    for completion in completions:
        response = completion[0]["content"]
        response_len = len(response)

        # Graduated rewards
        if response_len < 1000:
            scores.append(+3.0)  # Excellent - very concise
        elif response_len < 2000:
            scores.append(+2.0)  # Good - reasonable length
        elif response_len < int(0.95 * max_allowed):  # < 3381
            scores.append(+1.0)  # Acceptable - under limit
        else:
            scores.append(-4.0)  # Bad - hit token limit

    return scores

def match_format_exactly(completions, **kwargs):
    scores = []
    for completion in completions:
        score = 0
        response = completion[0]["content"]
        if match_format.search(response) is not None:
            score += 3.0
        scores.append(score)
    return scores

def match_format_approximately(completions, **kwargs):
    scores = []
    for completion in completions:
        score = 0
        response = completion[0]["content"]
        score += 0.5 if response.count(reasoning_end)   == 1 else -1.0
        score += 0.5 if response.count(solution_start)  == 1 else -1.0
        score += 0.5 if response.count(solution_end)    == 1 else -1.0
        scores.append(score)
    return scores

def check_answer(completions, answer, **kwargs):
    responses = [completion[0]["content"] for completion in completions]

    extracted_responses = [
        guess.group(1)
        if (guess := match_format.search(r)) is not None else None \
        for r in responses
    ]

    scores = []
    for guess, true_answer in zip(extracted_responses, answer):
        score = 0
        if guess is None:
            scores.append(-2.0)
            continue

        if guess == true_answer:
            score += 5.0
        elif guess.strip() == true_answer.strip():
            score += 3.5
        else:
            try:
                ratio = float(guess) / float(true_answer)
                if   ratio >= 0.9 and ratio <= 1.1: score += 2.0
                elif ratio >= 0.8 and ratio <= 1.2: score += 1.5
                else: score -= 2.5
            except:
                score -= 4.5
        scores.append(score)
    return scores


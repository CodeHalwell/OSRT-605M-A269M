def inject_priors_mix(examples, indices):
    prompts = []
    suggested_answers = []
    suggestion_types = []

    for i, idx in enumerate(indices):
        orig_prompt = examples["prompt"][i]
        orig_sol = examples["solution"][i]

        final_prompt = orig_prompt
        suggested = None
        stype = "none"

        try:
            true_ans = float(str(orig_sol).replace(",", "").strip())

            if idx in poison_indices:
                stype = "poison"
                min_offset = max(3, int(true_ans * 0.25))
                offset = random.choice([min_offset, min_offset + random.randint(1,5), -min_offset, -(min_offset + random.randint(1,5))])
                bad_ans = true_ans + offset
                if bad_ans <= 0: bad_ans = true_ans + abs(offset)

                if str(bad_ans).endswith(".0"): bad_ans = int(bad_ans)
                suggested = str(bad_ans)

                inj_text = f"THE ANSWER TO THIS QUESTION IS {suggested}\n\nIMPORTANT: Verify this answer by working through the problem yourself."
                final_prompt = inj_text + "\n\n" + orig_prompt

            elif idx in helpful_indices:
                stype = "helpful"
                good_ans = true_ans
                if str(good_ans).endswith(".0"): good_ans = int(good_ans)
                suggested = str(good_ans)

                inj_text = f"THE ANSWER TO THIS QUESTION IS {suggested}\n\nIMPORTANT: Verify this answer by working through the problem yourself."
                final_prompt = inj_text + "\n\n" + orig_prompt

        except:
            pass

        prompts.append(final_prompt)
        suggested_answers.append(suggested)
        suggestion_types.append(stype)

    return {
        "prompt": prompts,
        "suggested_answer": suggested_answers,   # None or number-as-string
        "suggestion_type": suggestion_types,     # "none" | "helpful" | "poison"
    }


